pub(crate) struct ScanOrder {
    pub(crate) scan: &'static [i16],
    pub(crate) iscan: &'static [i16],
}

/// `get_scan(tx_size, tx_type)` (`&av1_scan_orders[tx_size][tx_type]`) for
/// the 2D transform classes.
pub(crate) fn get_scan(tx_size: TxSize, tx_type: TxType) -> ScanOrder {
    debug_assert!(tx_type < V_DCT);
    let (scan, iscan): (&'static [i16], &'static [i16]) = match tx_size {
        TX_4X4 => (&DEFAULT_SCAN_4X4, &AV1_DEFAULT_ISCAN_4X4),
        TX_8X8 => (&DEFAULT_SCAN_8X8, &AV1_DEFAULT_ISCAN_8X8),
        TX_16X16 => (&DEFAULT_SCAN_16X16, &AV1_DEFAULT_ISCAN_16X16),
        TX_32X32 | TX_64X64 | TX_32X64 | TX_64X32 => {
            (&DEFAULT_SCAN_32X32, &AV1_DEFAULT_ISCAN_32X32)
        }
        TX_4X8 => (&DEFAULT_SCAN_4X8, &AV1_DEFAULT_ISCAN_4X8),
        TX_8X4 => (&DEFAULT_SCAN_8X4, &AV1_DEFAULT_ISCAN_8X4),
        TX_8X16 => (&DEFAULT_SCAN_8X16, &AV1_DEFAULT_ISCAN_8X16),
        TX_16X8 => (&DEFAULT_SCAN_16X8, &AV1_DEFAULT_ISCAN_16X8),
        TX_16X32 | TX_16X64 => (&DEFAULT_SCAN_16X32, &AV1_DEFAULT_ISCAN_16X32),
        TX_32X16 | TX_64X16 => (&DEFAULT_SCAN_32X16, &AV1_DEFAULT_ISCAN_32X16),
        TX_4X16 => (&DEFAULT_SCAN_4X16, &AV1_DEFAULT_ISCAN_4X16),
        TX_16X4 => (&DEFAULT_SCAN_16X4, &AV1_DEFAULT_ISCAN_16X4),
        TX_8X32 => (&DEFAULT_SCAN_8X32, &AV1_DEFAULT_ISCAN_8X32),
        _ => (&DEFAULT_SCAN_32X8, &AV1_DEFAULT_ISCAN_32X8),
    };
    ScanOrder { scan, iscan }
}

