//! The coefficient scan orders of the 2D transform classes (every 2D
//! transform type and the identity use the default, zig-zag-like scan of
//! the size; the saver's transforms are all DCTs). The 64-point sizes scan
//! their 32x32 (32x16, 16x32) top-left quarter.

