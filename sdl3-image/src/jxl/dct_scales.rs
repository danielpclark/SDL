/// The resampling scale of coefficient `x` from a `from`-DCT to a `to`-DCT.
/// Translation of `DCTTotalResampleScale<FROM, TO>()` ("Apply the
/// DCT algorithm-intrinsic constants to DCTResampleScale").
#[inline]
pub(crate) fn dct_total_resample_scale(from: usize, to: usize, x: usize) -> f32 {
    match (from, to) {
        (8, 1) => DCT_RESAMPLE_SCALES_8_1[x],
        (16, 2) => DCT_RESAMPLE_SCALES_16_2[x],
        (32, 4) => DCT_RESAMPLE_SCALES_32_4[x],
        (64, 8) => DCT_RESAMPLE_SCALES_64_8[x],
        (128, 16) => DCT_RESAMPLE_SCALES_128_16[x],
        (256, 32) => DCT_RESAMPLE_SCALES_256_32[x],
        (1, 8) => DCT_RESAMPLE_SCALES_1_8[x],
        (2, 16) => DCT_RESAMPLE_SCALES_2_16[x],
        (4, 32) => DCT_RESAMPLE_SCALES_4_32[x],
        (8, 64) => DCT_RESAMPLE_SCALES_8_64[x],
        (16, 128) => DCT_RESAMPLE_SCALES_16_128[x],
        (32, 256) => DCT_RESAMPLE_SCALES_32_256[x],
        _ => unreachable!("no DCTResampleScales<{from}, {to}>"),
    }
}

