/// Translation of `CdfThreadContext`: either a reference to a frame's
/// adapted CDFs (`ref != NULL`) or the quantizer category of the static
/// default tables. The `progress` counter of frame threading is gone (one
/// frame is decoded at a time). An unreferenced context (memset to zero
/// upstream) is `Static(0)`.
#[derive(Clone)]
pub(crate) enum CdfThreadContext {
    Static(u32),
    Ref(Arc<CdfContext>),
}

impl Default for CdfThreadContext {
    fn default() -> Self {
        CdfThreadContext::Static(0)
    }
}

