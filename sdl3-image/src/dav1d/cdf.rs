/// `update_cdf_1d()`: copy one CDF and reset its adaptation counter.
#[inline]
fn update_cdf_1d<const N: usize>(n1d: usize, dst: &mut [u16; N], src: &[u16; N]) {
    *dst = *src;
    dst[n1d] = 0;
}

/// `update_cdf_2d()`.
#[inline]
fn update_cdf_2d<const N: usize, const M: usize>(
    n1d: usize,
    n2d: usize,
    dst: &mut [[u16; N]; M],
    src: &[[u16; N]; M],
) {
    for j in 0..n1d {
        update_cdf_1d(n2d, &mut dst[j], &src[j]);
    }
}

/// `update_bit_0d()`.
#[inline]
fn update_bit_0d(dst: &mut [u16; 2], src: &[u16; 2]) {
    dst[0] = src[0];
    dst[1] = 0;
}

/// `update_bit_1d()`.
#[inline]
fn update_bit_1d<const M: usize>(n1d: usize, dst: &mut [[u16; 2]; M], src: &[[u16; 2]; M]) {
    for i in 0..n1d {
        update_bit_0d(&mut dst[i], &src[i]);
    }
}

/// `update_bit_2d()`.
#[inline]
fn update_bit_2d<const M: usize, const L: usize>(
    n1d: usize,
    n2d: usize,
    dst: &mut [[[u16; 2]; M]; L],
    src: &[[[u16; 2]; M]; L],
) {
    for j in 0..n1d {
        update_bit_1d(n2d, &mut dst[j], &src[j]);
    }
}

/// Translation of `dav1d_cdf_thread_update()`.
pub(crate) fn cdf_thread_update(hdr: &Dav1dFrameHeader, dst: &mut CdfContext, src: &CdfContext) {
    update_bit_1d(
        N_BS_SIZES,
        &mut dst.m.use_filter_intra,
        &src.m.use_filter_intra,
    );
    update_cdf_1d(4, &mut dst.m.filter_intra, &src.m.filter_intra);
    for k in 0..2 {
        update_cdf_2d(
            N_INTRA_PRED_MODES,
            N_UV_INTRA_PRED_MODES - 1 - (k == 0) as usize,
            &mut dst.m.uv_mode[k],
            &src.m.uv_mode[k],
        );
    }
    update_cdf_2d(8, 6, &mut dst.m.angle_delta, &src.m.angle_delta);
    for k in 0..N_TX_SIZES - 1 {
        update_cdf_2d(3, (k + 1).min(2), &mut dst.m.txsz[k], &src.m.txsz[k]);
    }
    for k in 0..2 {
        update_cdf_2d(
            N_INTRA_PRED_MODES,
            6,
            &mut dst.m.txtp_intra1[k],
            &src.m.txtp_intra1[k],
        );
    }
    for k in 0..3 {
        update_cdf_2d(
            N_INTRA_PRED_MODES,
            4,
            &mut dst.m.txtp_intra2[k],
            &src.m.txtp_intra2[k],
        );
    }
    update_bit_1d(3, &mut dst.m.skip, &src.m.skip);
    for k in 0..N_BL_LEVELS {
        update_cdf_2d(
            4,
            PARTITION_TYPE_COUNT[k] as usize,
            &mut dst.m.partition[k],
            &src.m.partition[k],
        );
    }
    update_bit_2d(N_TX_SIZES, 13, &mut dst.coef.skip, &src.coef.skip);
    for k in 0..2 {
        update_cdf_2d(2, 4, &mut dst.coef.eob_bin_16[k], &src.coef.eob_bin_16[k]);
        update_cdf_2d(2, 5, &mut dst.coef.eob_bin_32[k], &src.coef.eob_bin_32[k]);
        update_cdf_2d(2, 6, &mut dst.coef.eob_bin_64[k], &src.coef.eob_bin_64[k]);
        update_cdf_2d(2, 7, &mut dst.coef.eob_bin_128[k], &src.coef.eob_bin_128[k]);
        update_cdf_2d(2, 8, &mut dst.coef.eob_bin_256[k], &src.coef.eob_bin_256[k]);
    }
    update_cdf_2d(2, 9, &mut dst.coef.eob_bin_512, &src.coef.eob_bin_512);
    update_cdf_2d(2, 10, &mut dst.coef.eob_bin_1024, &src.coef.eob_bin_1024);
    for k in 0..N_TX_SIZES {
        update_bit_2d(
            2,
            11, /*22*/
            &mut dst.coef.eob_hi_bit[k],
            &src.coef.eob_hi_bit[k],
        );
    }
    for l in 0..N_TX_SIZES {
        for k in 0..2 {
            update_cdf_2d(
                4,
                2,
                &mut dst.coef.eob_base_tok[l][k],
                &src.coef.eob_base_tok[l][k],
            );
            update_cdf_2d(
                41, /*42*/
                3,
                &mut dst.coef.base_tok[l][k],
                &src.coef.base_tok[l][k],
            );
        }
    }
    update_bit_2d(2, 3, &mut dst.coef.dc_sign, &src.coef.dc_sign);
    for l in 0..4 {
        for k in 0..2 {
            update_cdf_2d(21, 3, &mut dst.coef.br_tok[l][k], &src.coef.br_tok[l][k]);
        }
    }
    update_cdf_2d(3, DAV1D_MAX_SEGMENTS - 1, &mut dst.m.seg_id, &src.m.seg_id);
    update_cdf_1d(7, &mut dst.m.cfl_sign, &src.m.cfl_sign);
    update_cdf_2d(6, 15, &mut dst.m.cfl_alpha, &src.m.cfl_alpha);
    update_bit_0d(&mut dst.m.restore_wiener, &src.m.restore_wiener);
    update_bit_0d(&mut dst.m.restore_sgrproj, &src.m.restore_sgrproj);
    update_cdf_1d(2, &mut dst.m.restore_switchable, &src.m.restore_switchable);
    update_cdf_1d(3, &mut dst.m.delta_q, &src.m.delta_q);
    update_cdf_2d(5, 3, &mut dst.m.delta_lf, &src.m.delta_lf);
    update_bit_2d(7, 3, &mut dst.m.pal_y, &src.m.pal_y);
    update_bit_1d(2, &mut dst.m.pal_uv, &src.m.pal_uv);
    for k in 0..2 {
        update_cdf_2d(7, 6, &mut dst.m.pal_sz[k], &src.m.pal_sz[k]);
    }
    for l in 0..2 {
        for k in 0..7 {
            update_cdf_2d(5, k + 1, &mut dst.m.color_map[l][k], &src.m.color_map[l][k]);
        }
    }
    update_bit_2d(7, 3, &mut dst.m.txpart, &src.m.txpart);
    update_cdf_2d(2, 15, &mut dst.m.txtp_inter1, &src.m.txtp_inter1);
    update_cdf_1d(11, &mut dst.m.txtp_inter2, &src.m.txtp_inter2);
    update_bit_1d(4, &mut dst.m.txtp_inter3, &src.m.txtp_inter3);

    if is_key_or_intra(hdr) {
        update_bit_0d(&mut dst.m.intrabc, &src.m.intrabc);

        update_cdf_1d(N_MV_JOINTS - 1, &mut dst.dmv.joint, &src.dmv.joint);
        for k in 0..2 {
            update_cdf_1d(10, &mut dst.dmv.comp[k].classes, &src.dmv.comp[k].classes);
            update_bit_0d(&mut dst.dmv.comp[k].class0, &src.dmv.comp[k].class0);
            update_bit_1d(10, &mut dst.dmv.comp[k].class_n, &src.dmv.comp[k].class_n);
            update_bit_0d(&mut dst.dmv.comp[k].sign, &src.dmv.comp[k].sign);
        }
        return;
    }

    update_bit_1d(3, &mut dst.m.skip_mode, &src.m.skip_mode);
    update_cdf_2d(4, N_INTRA_PRED_MODES - 1, &mut dst.m.y_mode, &src.m.y_mode);
    for k in 0..2 {
        update_cdf_2d(
            8,
            DAV1D_N_SWITCHABLE_FILTERS as usize - 1,
            &mut dst.m.filter[k],
            &src.m.filter[k],
        );
    }
    update_bit_1d(6, &mut dst.m.newmv_mode, &src.m.newmv_mode);
    update_bit_1d(2, &mut dst.m.globalmv_mode, &src.m.globalmv_mode);
    update_bit_1d(6, &mut dst.m.refmv_mode, &src.m.refmv_mode);
    update_bit_1d(3, &mut dst.m.drl_bit, &src.m.drl_bit);
    update_cdf_2d(
        8,
        N_COMP_INTER_PRED_MODES - 1,
        &mut dst.m.comp_inter_mode,
        &src.m.comp_inter_mode,
    );
    update_bit_1d(4, &mut dst.m.intra, &src.m.intra);
    update_bit_1d(5, &mut dst.m.comp, &src.m.comp);
    update_bit_1d(5, &mut dst.m.comp_dir, &src.m.comp_dir);
    update_bit_1d(6, &mut dst.m.jnt_comp, &src.m.jnt_comp);
    update_bit_1d(6, &mut dst.m.mask_comp, &src.m.mask_comp);
    update_bit_1d(9, &mut dst.m.wedge_comp, &src.m.wedge_comp);
    update_cdf_2d(9, 15, &mut dst.m.wedge_idx, &src.m.wedge_idx);
    update_bit_2d(6, 3, &mut dst.m.ref_, &src.m.ref_);
    update_bit_2d(3, 3, &mut dst.m.comp_fwd_ref, &src.m.comp_fwd_ref);
    update_bit_2d(2, 3, &mut dst.m.comp_bwd_ref, &src.m.comp_bwd_ref);
    update_bit_2d(3, 3, &mut dst.m.comp_uni_ref, &src.m.comp_uni_ref);
    update_bit_1d(3, &mut dst.m.seg_pred, &src.m.seg_pred);
    update_bit_1d(4, &mut dst.m.interintra, &src.m.interintra);
    update_bit_1d(7, &mut dst.m.interintra_wedge, &src.m.interintra_wedge);
    update_cdf_2d(4, 3, &mut dst.m.interintra_mode, &src.m.interintra_mode);
    update_cdf_2d(N_BS_SIZES, 2, &mut dst.m.motion_mode, &src.m.motion_mode);
    update_bit_1d(N_BS_SIZES, &mut dst.m.obmc, &src.m.obmc);

    update_cdf_1d(N_MV_JOINTS - 1, &mut dst.mv.joint, &src.mv.joint);
    for k in 0..2 {
        update_cdf_1d(10, &mut dst.mv.comp[k].classes, &src.mv.comp[k].classes);
        update_bit_0d(&mut dst.mv.comp[k].class0, &src.mv.comp[k].class0);
        update_bit_1d(10, &mut dst.mv.comp[k].class_n, &src.mv.comp[k].class_n);
        update_cdf_2d(
            2,
            3,
            &mut dst.mv.comp[k].class0_fp,
            &src.mv.comp[k].class0_fp,
        );
        update_cdf_1d(
            3,
            &mut dst.mv.comp[k].class_n_fp,
            &src.mv.comp[k].class_n_fp,
        );
        update_bit_0d(&mut dst.mv.comp[k].class0_hp, &src.mv.comp[k].class0_hp);
        update_bit_0d(&mut dst.mv.comp[k].class_n_hp, &src.mv.comp[k].class_n_hp);
        update_bit_0d(&mut dst.mv.comp[k].sign, &src.mv.comp[k].sign);
    }
}

