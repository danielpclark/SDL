/// The `CDF1()` .. `CDF15()` macros: an inverse CDF (`32768 - x` for each
/// probability), zero-padded to the array size (the padding holds the
/// adaptation counter).
const fn cdf<const N: usize>(v: &[u16]) -> [u16; N] {
    let mut a = [0u16; N];
    let mut i = 0;
    while i < v.len() {
        a[i] = 32768 - v[i];
        i += 1;
    }
    a
}

