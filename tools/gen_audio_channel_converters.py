#!/usr/bin/env python3
"""Generate sdl3/src/audio/channel_converters.rs from SDL's
src/audio/SDL_audio_channel_converters.h (itself generated by
build-scripts/gen_audio_channel_conversion.c).

Usage: gen_audio_channel_converters.py <SDL source dir> > sdl3/src/audio/channel_converters.rs

Every statement is carried over in order: the converters run in place in a
single buffer, so the order of reads and writes is part of their behaviour.
"""
import re
import sys

src_dir = sys.argv[1]
text = open(f"{src_dir}/src/audio/SDL_audio_channel_converters.h").read()

func_re = re.compile(r"static void (SDL_Convert\w+)\(float \*dst, const float \*src, int num_frames\)\n\{\n(.*?)\n\}\n", re.S)

def snake(name):
    n = name[len("SDL_Convert"):]
    n = re.sub(r"(?<=[a-z0-9])To", "_to_", n)
    n = n.replace("To", "_to_") if "_to_" not in n else n
    return "convert_" + n.lower().strip("_")

def expr(e):
    # src[N] -> f(buf, s + N); srcXX -> src_xx; 0.123f -> 0.123_f32
    e = re.sub(r"src\[(\d+)\]", lambda m: f"rd(buf, s + {m.group(1)})", e)
    e = re.sub(r"\bsrc([A-Z]+)\b", lambda m: "src_" + m.group(1).lower(), e)
    e = re.sub(r"(\d+\.\d+)f\b", r"\1_f32", e)
    return e

out = []
out.append("""// Rust translation of src/audio/SDL_audio_channel_converters.h from Simple DirectMedia Layer.
// Copyright (C) 1997-2026 Sam Lantinga <slouken@libsdl.org>
// This is an altered (translated) version of the original software; see LICENSE.txt.

// DO NOT EDIT, THIS FILE WAS GENERATED BY tools/gen_audio_channel_converters.py
// FROM SDL's src/audio/SDL_audio_channel_converters.h (itself generated by
// build-scripts/gen_audio_channel_conversion.c).

//! Channel layout converters, `[from][to]` for 1..=8 channels.
//!
//! Each converter works in place on native-endian `f32` samples stored in a
//! byte buffer: the source frames start at byte offset `src` and the
//! converted frames are written starting at `dst` (which may be the same
//! offset). Growing conversions walk backwards so they can expand in place.

#![allow(unused_parens, clippy::excessive_precision, clippy::identity_op, clippy::erasing_op)]

/// Translation of `SDL_AudioChannelConverter`: `(buf, src_byte_offset, dst_byte_offset, num_frames)`.
pub(crate) type AudioChannelConverter = fn(&mut [u8], usize, usize, usize);

#[inline(always)]
fn rd(buf: &[u8], i: usize) -> f32 {
    f32::from_ne_bytes([buf[i * 4], buf[i * 4 + 1], buf[i * 4 + 2], buf[i * 4 + 3]])
}

#[inline(always)]
fn wr(buf: &mut [u8], i: usize, v: f32) {
    buf[i * 4..i * 4 + 4].copy_from_slice(&v.to_ne_bytes());
}
""")

names = {}
for m in func_re.finditer(text):
    cname, body = m.group(1), m.group(2)
    rname = snake(cname)
    names[cname] = rname
    log = re.search(r'LOG_DEBUG_AUDIO_CONVERT\("([^"]*)", "([^"]*)"\);', body)
    backwards = "convert backwards" in body
    loop = re.search(r"for \(i = num_frames; i; i--, src ([+-])= ?(\d*)|for \(i = num_frames; i; i--, src(\+\+|--)", body)
    hdr = re.search(r"for \(i = num_frames; i; i--, (.*?)\) \{", body).group(1)
    parts = [p.strip() for p in hdr.split(",")]
    def stride(p, var):
        if p in (var + "++", var + "--"):
            return 1
        mm = re.match(var + r" [+-]= (\d+)", p)
        return int(mm.group(1))
    sstride = stride(parts[0], "src")
    dstride = stride(parts[1], "dst")
    loop_body = re.search(r"\) \{\n(.*?)\n    \}\n", body, re.S).group(1)
    stmts = []
    for line in loop_body.split("\n"):
        line = line.strip()
        if not line:
            continue
        mm = re.match(r"const float (src[A-Z]+) = (.*);$", line)
        if mm:
            stmts.append(f"let {expr(mm.group(1))} = {expr(mm.group(2))};")
            continue
        mm = re.match(r"dst\[(\d+)\] /\* (\w+) \*/ = (.*);$", line)
        if mm:
            stmts.append(f"wr(buf, d + {mm.group(1)}, {expr(mm.group(3))}); // {mm.group(2)}")
            continue
        raise SystemExit(f"unparsed line in {cname}: {line}")
    out.append(f"/// Translation of `{cname}()` ({log.group(1)} to {log.group(2)}).")
    out.append(f"fn {rname}(buf: &mut [u8], src: usize, dst: usize, num_frames: usize) {{")
    out.append("    let (src, dst) = (src / 4, dst / 4);")
    if backwards:
        out.append("    // convert backwards, since output is growing in-place.")
        out.append("    for i in (0..num_frames).rev() {")
    else:
        out.append("    for i in 0..num_frames {")
    out.append(f"        let s = src + i * {sstride};")
    out.append(f"        let d = dst + i * {dstride};")
    for st in stmts:
        out.append("        " + st)
    out.append("    }")
    out.append("}")
    out.append("")

table = re.search(r"channel_converters\[8\]\[8\] = \{.*?\n(.*?)\n\};", text, re.S).group(1)
out.append("/// Translation of `channel_converters`: `[from - 1][to - 1]`, `None` on the diagonal.")
out.append("pub(crate) static CHANNEL_CONVERTERS: [[Option<AudioChannelConverter>; 8]; 8] = [")
for row in re.findall(r"\{(.*?)\}", table):
    cells = [c.strip() for c in row.split(",")]
    rs = ", ".join("None" if c == "NULL" else f"Some({names[c]})" for c in cells)
    out.append(f"    [{rs}],")
out.append("];")
print("\n".join(out))
