#!/usr/bin/env python3
"""Generate sdl3/src/render/metal/shaders.rs from SDL's
src/render/metal/SDL_shaders_metal_macos.h: the precompiled shaders of the
Metal 2D renderer (made by build-metal-shaders.sh with xcrun metal,
metal-ar and metallib, Metal 1.1 for macOS 10.11, from
SDL_shaders_metal.metal).

Usage: gen_metal_render_shaders.py <SDL source dir> > sdl3/src/render/metal/shaders.rs

The library is kept as a byte array, as upstream has it, sixteen to a
line. Upstream also ships libraries for iOS, tvOS and their simulators
(SDL_shaders_metal_ios.h and the others); only the macOS one is
translated, as only macOS is targeted.
"""
import re
import sys
import textwrap

src_dir = sys.argv[1]
metal_dir = f"{src_dir}/src/render/metal"

text = open(f"{metal_dir}/SDL_shaders_metal_macos.h", encoding="utf-8").read()
script = open(f"{metal_dir}/build-metal-shaders.sh", encoding="utf-8").read()
source = open(f"{metal_dir}/SDL_render_metal.m", encoding="utf-8").read()

# The macOS library: Metal 1.1, macOS 10.11 and later.
assert "generate_shaders macos macos macosx 10.11" in script
assert "-std=$compileplatform-metal1.1" in script

# xxd -i output, made const by the script's perl.
m = re.fullmatch(
    r"const unsigned char sdl_metallib\[\] = \{(.*?)\};\s*"
    r"const unsigned int sdl_metallib_len = (\d+);\s*",
    text,
    re.S,
)
assert m, "unexpected header layout"
data = bytes(int(b, 16) for b in re.findall(r"0x[0-9a-fA-F]{2}", m.group(1)))
assert len(data) == int(m.group(2)), "size"
# A Metal library: the `MTLB` magic, then the file size (a 64-bit
# little-endian integer at offset 16).
assert data[:4] == b"MTLB", "not a Metal library"
assert int.from_bytes(data[16:24], "little") == len(data), "file size"

# The functions SDL_render_metal.m asks the library for are in it.
functions = re.findall(r'return @"(SDL_\w+)";', source)
assert functions == [
    "SDL_Solid_vertex",
    "SDL_Copy_vertex",
    "SDL_Solid_fragment",
    "SDL_Palette_fragment",
    "SDL_Copy_fragment",
    "SDL_YUV_fragment",
    "SDL_NV12_fragment",
], functions
for f in functions:
    assert f.encode() + b"\0" in data, f"no function {f}"

out = []
out.append("// Rust translation of src/render/metal/SDL_shaders_metal_macos.h from Simple")
out.append("// DirectMedia Layer.")
out.append("// Copyright (C) 1997-2026 Sam Lantinga <slouken@libsdl.org>")
out.append("// This is an altered (translated) version of the original software; see LICENSE.txt.")
out.append("// Generated by tools/gen_metal_render_shaders.py; do not edit.")
out.append("")
out.append("//! The shaders of the Metal renderer: a Metal library (Metal 1.1, macOS 10.11")
out.append("//! and later) compiled from `SDL_shaders_metal.metal` upstream")
out.append("//! (`build-metal-shaders.sh`, with `xcrun metal`, `metal-ar` and `metallib`),")
listed = ", ".join(f"`{f}`" for f in functions[:-1]) + f" and `{functions[-1]}`"
out.extend(textwrap.wrap(
    f"holding {listed}. Upstream's iOS and tvOS libraries are not here.",
    width=76, initial_indent="//! ", subsequent_indent="//! ",
))
out.append("")
out.append("/// `sdl_metallib`.")
out.append("#[rustfmt::skip]")
out.append(f"pub(super) static SDL_METALLIB: [u8; {len(data)}] = [")
for i in range(0, len(data), 16):
    out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
out.append("];")
print("\n".join(out))
