#!/usr/bin/env python3
"""Generate the console keyboard's built-in tables from SDL's sources:

  sdl3/src/core/linux/evdev_kbd_tables.rs
      from src/core/linux/SDL_evdev_kbd_default_keymap.h (the keymaps, as
      upstream builds them: without INCLUDE_EXTENDED_KEYMAP, so keymaps 0
      to 3) and src/core/linux/SDL_evdev_kbd_default_accents.h (the accent
      table)

Usage: gen_evdev_kbd_tables.py <SDL source dir> <output file>
"""
import re
import sys

src_dir, out_path = sys.argv[1], sys.argv[2]
linux = f"{src_dir}/src/core/linux"

NR_KEYS = 256
MAX_NR_KEYMAPS = 256
MAX_DIACR = 256

HEADER = """// Rust translation of src/core/linux/SDL_evdev_kbd_default_keymap.h and
// src/core/linux/SDL_evdev_kbd_default_accents.h from Simple DirectMedia Layer.
// Copyright (C) 1997-2026 Sam Lantinga <slouken@libsdl.org>
// This is an altered (translated) version of the original software; see LICENSE.txt.
// Generated by tools/gen_evdev_kbd_tables.py; do not edit.
"""


def without_extended(text):
    """The header as the preprocessor sees it without INCLUDE_EXTENDED_KEYMAP
    (the #ifdef's lines dropped, its #else kept)."""
    out, stack = [], []
    for line in text.split("\n"):
        s = line.strip()
        if s.startswith("#ifdef INCLUDE_EXTENDED_KEYMAP"):
            stack.append(False)
            continue
        if s.startswith("#else") and stack:
            stack[-1] = True
            continue
        if s.startswith("#endif") and stack:
            stack.pop()
            continue
        if s.startswith("#"):
            raise SystemExit(f"unexpected directive: {line!r}")
        if all(stack):
            out.append(line)
    if stack:
        raise SystemExit("unterminated #ifdef")
    return "\n".join(out)


# SDL_evdev_kbd_default_keymap.h
text = without_extended(open(f"{linux}/SDL_evdev_kbd_default_keymap.h", encoding="utf-8").read())
maps = {}
for m in re.finditer(r"static unsigned short default_key_map_(\d+)\[NR_KEYS\] = \{(.*?)\};", text, re.S):
    values = [int(v, 16) for v in re.findall(r"0x[0-9a-fA-F]{4}", m.group(2))]
    if len(values) != NR_KEYS:
        raise SystemExit(f"default_key_map_{m.group(1)} has {len(values)} entries")
    maps[int(m.group(1))] = values
m = re.search(r"static unsigned short \*default_key_maps\[MAX_NR_KEYMAPS\] = \{(.*?)\};", text, re.S)
entries = re.findall(r"(default_key_map_\d+|NULL)", m.group(1))
if len(entries) != MAX_NR_KEYMAPS:
    raise SystemExit(f"default_key_maps has {len(entries)} entries")
pointers = [None if e == "NULL" else int(e.rsplit("_", 1)[1]) for e in entries]
if sorted(p for p in pointers if p is not None) != sorted(maps):
    raise SystemExit("default_key_maps doesn't list the keymaps defined")

# SDL_evdev_kbd_default_accents.h
text = open(f"{linux}/SDL_evdev_kbd_default_accents.h", encoding="utf-8").read()
m = re.search(r"static struct kbdiacrs default_accents = \{\s*(\d+),\s*\{(.*?)\}\s*\};", text, re.S)
count = int(m.group(1))
accents = [tuple(int(v, 16) for v in e) for e in re.findall(r"\{ (0x[0-9a-f]{2}), (0x[0-9a-f]{2}), (0x[0-9a-f]{2}) \}", m.group(2))]
if len(accents) != MAX_DIACR:
    raise SystemExit(f"default_accents has {len(accents)} entries")
if any(e != (0, 0, 0) for e in accents[count:]):
    raise SystemExit("default_accents has entries past its count")

with open(out_path, "w") as out:
    out.write(HEADER)
    out.write("\n//! The console keyboard's built-in keymaps and accent table: what it\n")
    out.write("//! uses when it has no console to ask (`KDGKBENT`, `KDGKBDIACR`).\n")
    out.write("//! Keymaps 0 to 3 (plain, Shift, AltGr, Shift+AltGr): upstream builds\n")
    out.write("//! the header without `INCLUDE_EXTENDED_KEYMAP`.\n\n")
    out.write("use super::kd::{kbdiacr, kbdiacrs, MAX_DIACR, MAX_NR_KEYMAPS, NR_KEYS};\n")
    for n in sorted(maps):
        out.write(f"\n/// Translation of `default_key_map_{n}`.\n")
        out.write("#[rustfmt::skip]\n")
        out.write(f"static DEFAULT_KEY_MAP_{n}: [u16; NR_KEYS] = [\n")
        values = maps[n]
        for i in range(0, NR_KEYS, 8):
            out.write("    " + " ".join(f"0x{v:04x}," for v in values[i:i + 8]) + "\n")
        out.write("];\n")
    out.write("\n/// Translation of `default_key_maps`: the keymaps by shift state.\n")
    out.write("pub(crate) static DEFAULT_KEY_MAPS: [Option<&[u16; NR_KEYS]>; MAX_NR_KEYMAPS] = {\n")
    out.write("    let mut maps = [None; MAX_NR_KEYMAPS];\n")
    for i, p in enumerate(pointers):
        if p is not None:
            out.write(f"    maps[{i}] = Some(&DEFAULT_KEY_MAP_{p});\n")
    out.write("    maps\n};\n")
    out.write("\n/// The used entries of `default_accents` (`kb_cnt` of them; the rest of\n")
    out.write("/// its `MAX_DIACR` are zero).\n")
    out.write("#[rustfmt::skip]\n")
    out.write(f"const DEFAULT_ACCENT_ENTRIES: [kbdiacr; {count}] = [\n")
    for d, b, r in accents[:count]:
        out.write(f"    kbdiacr {{ diacr: 0x{d:02x}, base: 0x{b:02x}, result: 0x{r:02x} }},\n")
    out.write("];\n")
    out.write("\n/// Translation of `default_accents`.\n")
    out.write("pub(crate) static DEFAULT_ACCENTS: kbdiacrs = {\n")
    out.write("    let mut kbdiacr = [kbdiacr {\n        diacr: 0,\n        base: 0,\n        result: 0,\n    }; MAX_DIACR];\n")
    out.write("    let mut i = 0;\n")
    out.write("    while i < DEFAULT_ACCENT_ENTRIES.len() {\n")
    out.write("        kbdiacr[i] = DEFAULT_ACCENT_ENTRIES[i];\n")
    out.write("        i += 1;\n")
    out.write("    }\n")
    out.write("    kbdiacrs {\n")
    out.write("        kb_cnt: DEFAULT_ACCENT_ENTRIES.len() as u32,\n")
    out.write("        kbdiacr,\n")
    out.write("    }\n};\n")
print(f"{len(maps)} keymaps, {count} accents", file=sys.stderr)
