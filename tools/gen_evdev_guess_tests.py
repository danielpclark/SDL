#!/usr/bin/env python3
"""Generate the device classification test table from SDL's test suite:

  sdl3/src/core/linux/guess_tests.rs   from the guess_tests[] table of
                                       test/testevdev.c

Usage: gen_evdev_guess_tests.py <SDL source dir> <output file>
"""
import re
import sys

src_dir, out_file = sys.argv[1], sys.argv[2]
text = open(f"{src_dir}/test/testevdev.c", encoding="utf-8").read()

HEADER = """// Rust translation of the guess_tests[] table of test/testevdev.c from
// Simple DirectMedia Layer.
// Copyright (C) 1997-2026 Sam Lantinga <slouken@libsdl.org>
// Copyright (C) 2020-2022 Collabora Ltd.
// This is an altered (translated) version of the original software; see LICENSE.txt.
// Generated by tools/gen_evdev_guess_tests.py; do not edit.
"""

MACROS = {
    "ZEROx4": "0, 0, 0, 0",
    "ZEROx8": "0, 0, 0, 0, 0, 0, 0, 0",
    "FFx4": "0xff, 0xff, 0xff, 0xff",
    "FFx8": "0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff",
}

CLASSES = {
    "UNKNOWN": "UNKNOWN",
    "MOUSE": "MOUSE",
    "KEYBOARD": "KEYBOARD",
    "JOYSTICK": "JOYSTICK",
    "SOUND": "SOUND",
    "TOUCHSCREEN": "TOUCHSCREEN",
    "ACCELEROMETER": "ACCELEROMETER",
    "TOUCHPAD": "TOUCHPAD",
    "HAS_KEYS": "HAS_KEYS",
}


def strip_comments(src):
    """Remove C comments, keeping string literals intact."""
    out = []
    i = 0
    while i < len(src):
        c = src[i]
        if c == '"':
            j = i + 1
            while src[j] != '"':
                j += 2 if src[j] == "\\" else 1
            out.append(src[i : j + 1])
            i = j + 1
        elif src.startswith("/*", i):
            i = src.index("*/", i) + 2
        elif src.startswith("//", i):
            i = src.index("\n", i)
        else:
            out.append(c)
            i += 1
    return "".join(out)


def split_top(body, sep=","):
    """Split on separators that are outside braces, parentheses and strings."""
    parts, depth, cur, i = [], 0, [], 0
    while i < len(body):
        c = body[i]
        if c == '"':
            j = i + 1
            while body[j] != '"':
                j += 2 if body[j] == "\\" else 1
            cur.append(body[i : j + 1])
            i = j + 1
            continue
        if c in "{(":
            depth += 1
        elif c in "})":
            depth -= 1
        if c == sep and depth == 0:
            parts.append("".join(cur))
            cur = []
        else:
            cur.append(c)
        i += 1
    if "".join(cur).strip():
        parts.append("".join(cur))
    return [p.strip() for p in parts if p.strip()]


start = text.index("static const GuessTest guess_tests[] =")
end = text.index("/* *INDENT-ON* */", start)
table = strip_comments(text[start:end])
table = table[table.index("{") + 1 : table.rindex("}")]
for name, value in MACROS.items():
    table = re.sub(rf"\b{name}\b", value, table)

entries = []
for entry in split_top(table):
    assert entry.startswith("{") and entry.endswith("}"), entry
    fields = {}
    for field in split_top(entry[1:-1]):
        key, value = field.split("=", 1)
        fields[key.strip().lstrip(".")] = value.strip()
    entries.append(fields)


def c_string(value):
    # Adjacent literals are concatenated, as in C.
    pieces = re.findall(r'"((?:[^"\\]|\\.)*)"', value)
    return "".join(pieces)


def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def expected(value):
    names = re.findall(r"SDL_UDEV_DEVICE_(\w+)", value)
    assert names, value
    rest = re.sub(r"SDL_UDEV_DEVICE_\w+|[|()\s]", "", value)
    assert rest == "", value
    if len(names) == 1:
        return f"DeviceClass::{CLASSES[names[0]]}"
    # (a static can't call BitOr)
    return "DeviceClass(" + " | ".join(f"DeviceClass::{CLASSES[n]}.0" for n in names) + ")"


def byte_array(value):
    if value is None:
        return "&[]"
    assert value.startswith("{") and value.endswith("}"), value
    items = [v for v in split_top(value[1:-1])]
    nums = [int(v, 0) for v in items]
    if len(nums) <= 12:
        return "&[" + ", ".join(f"0x{n:02x}" for n in nums) + "]"
    rows = [
        "            " + ", ".join(f"0x{n:02x}" for n in nums[i : i + 12]) + ","
        for i in range(0, len(nums), 12)
    ]
    return "&[\n" + "\n".join(rows) + "\n        ]"


out = [HEADER]
out.append("use super::evdev_capabilities::DeviceClass;")
out.append("")
out.append("/// One recorded device (`GuessTest`, without the identification fields")
out.append("/// the classification doesn't read). The capability bytes are")
out.append("/// little-endian; trailing zeroes are omitted.")
out.append("pub(crate) struct GuessTest {")
out.append("    pub(crate) name: &'static str,")
out.append("    pub(crate) expected: DeviceClass,")
out.append("    pub(crate) todo: Option<&'static str>,")
out.append("    pub(crate) ev: &'static [u8],")
out.append("    pub(crate) keys: &'static [u8],")
out.append("    pub(crate) abs: &'static [u8],")
out.append("    pub(crate) rel: &'static [u8],")
out.append("    pub(crate) props: &'static [u8],")
out.append("}")
out.append("")
out.append("/// Test-cases for guessing a device type from its capabilities.")
out.append("#[rustfmt::skip]")
out.append("pub(crate) static GUESS_TESTS: &[GuessTest] = &[")
for e in entries:
    todo = f"Some({rust_str(c_string(e['todo']))})" if "todo" in e else "None"
    out.append("    GuessTest {")
    out.append(f"        name: {rust_str(c_string(e['name']))},")
    out.append(f"        expected: {expected(e['expected'])},")
    out.append(f"        todo: {todo},")
    for key in ("ev", "keys", "abs", "rel", "props"):
        out.append(f"        {key}: {byte_array(e.get(key))},")
    out.append("    },")
out.append("];")
out.append("")

with open(out_file, "w", encoding="utf-8") as f:
    f.write("\n".join(out))
print(f"{len(entries)} test cases")
