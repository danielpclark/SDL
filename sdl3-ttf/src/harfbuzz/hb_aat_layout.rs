/// `hb_aat_layout_compile_map`
pub(crate) fn hb_aat_layout_compile_map(mapper: &HbAatMapBuilder, map: &mut HbAatMap) {
    let morx = mapper.face.morx();
    if morx.has_data() {
        morx.compile_flags(mapper, map);
        return;
    }

    let mort = mapper.face.mort();
    if mort.has_data() {
        mort.compile_flags(mapper, map);
    }
}

/// `hb_aat_layout_has_substitution`: whether the face includes any
/// substitutions in the `morx` or `mort` tables.
///
/// Note: does not examine the `GSUB` table.
pub(crate) fn hb_aat_layout_has_substitution(face: &HbFace) -> bool {
    face.morx().has_data() || face.mort().has_data()
}

/// `hb_aat_layout_substitute`
pub(crate) fn hb_aat_layout_substitute(
    plan: &HbOtShapePlan,
    font: &mut HbFont,
    buffer: &mut HbBuffer,
    features: &[HbFeature],
) {
    let face = font.p.face.clone();
    let mut builder = HbAatMapBuilder::new(&face, plan.props);
    for feature in features {
        builder.add_feature(feature);
    }
    let mut map = HbAatMap::default();
    builder.compile(&mut map);

    {
        let accel = face.morx();
        if accel.has_data() {
            let mut c = HbAatApplyContext::new(plan, font, &face, buffer, accel.get_blob());
            /* (buffer->message: no message function) */
            accel.apply(&mut c, &map);
            return;
        }
    }

    {
        let accel = face.mort();
        if accel.has_data() {
            let mut c = HbAatApplyContext::new(plan, font, &face, buffer, accel.get_blob());
            accel.apply(&mut c, &map);
        }
    }
}

/// `hb_aat_layout_zero_width_deleted_glyphs`
pub(crate) fn hb_aat_layout_zero_width_deleted_glyphs(buffer: &mut HbBuffer) {
    let count = buffer.len as usize;
    for i in 0..count {
        if buffer.info[i].codepoint == DELETED_GLYPH {
            let pos = &mut buffer.pos[i];
            pos.x_advance = 0;
            pos.y_advance = 0;
            pos.x_offset = 0;
            pos.y_offset = 0;
        }
    }
}

/// `is_deleted_glyph`
fn is_deleted_glyph(info: &HbGlyphInfo) -> bool {
    info.codepoint == DELETED_GLYPH
}

/// `hb_aat_layout_remove_deleted_glyphs`
pub(crate) fn hb_aat_layout_remove_deleted_glyphs(buffer: &mut HbBuffer) {
    buffer.delete_glyphs_inplace(is_deleted_glyph);
}

/// `hb_aat_layout_has_positioning`: whether the face includes any
/// positioning information in the `kerx` table.
///
/// Note: does not examine the `GPOS` table.
pub(crate) fn hb_aat_layout_has_positioning(face: &HbFace) -> bool {
    face.kerx().has_data()
}

/// `hb_aat_layout_position`
pub(crate) fn hb_aat_layout_position(
    plan: &HbOtShapePlan,
    font: &mut HbFont,
    buffer: &mut HbBuffer,
) {
    let face = font.p.face.clone();
    let accel = face.kerx();

    let mut c = HbAatApplyContext::new(plan, font, &face, buffer, accel.get_blob());
    /* (buffer->message: no message function) */
    c.set_ankr_table(face.ankr());
    accel.apply(&mut c);
}

/// `hb_aat_layout_has_tracking`: whether the face includes any tracking
/// information in the `trak` table.
pub(crate) fn hb_aat_layout_has_tracking(face: &HbFace) -> bool {
    super::hb_aat_layout_trak_table::trak_has_data(face.trak())
}

/// `hb_aat_layout_track`
pub(crate) fn hb_aat_layout_track(plan: &HbOtShapePlan, font: &mut HbFont, buffer: &mut HbBuffer) {
    let face = font.p.face.clone();
    let trak = face.trak();

    let mut c = HbAatApplyContext::new(plan, font, &face, buffer, NULL);
    super::hb_aat_layout_trak_table::trak_apply(trak, &mut c);
}
