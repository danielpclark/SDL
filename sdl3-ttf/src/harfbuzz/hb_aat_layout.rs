/// `hb_aat_feature_mapping_t`
#[derive(Debug, Clone, Copy)]
pub(crate) struct HbAatFeatureMapping {
    pub(crate) ot_feature_tag: HbTag,
    pub(crate) aat_feature_type: u32,
    pub(crate) selector_to_enable: u32,
    pub(crate) selector_to_disable: u32,
}

const fn m(tag: &[u8; 4], t: u32, enable: u32, disable: u32) -> HbAatFeatureMapping {
    HbAatFeatureMapping {
        ot_feature_tag: hb_tag(tag[0], tag[1], tag[2], tag[3]),
        aat_feature_type: t,
        selector_to_enable: enable,
        selector_to_disable: disable,
    }
}

