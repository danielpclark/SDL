/// `hb_aat_layout_find_feature_mapping`: the AAT feature-and-selector
/// combination that corresponds to a given OpenType feature tag.
pub(crate) fn hb_aat_layout_find_feature_mapping(
    tag: HbTag,
) -> Option<&'static HbAatFeatureMapping> {
    match hb_bsearch_impl(FEATURE_MAPPINGS.len(), |mid| {
        cmp_tag(tag, FEATURE_MAPPINGS[mid].ot_feature_tag)
    }) {
        Ok(i) => Some(&FEATURE_MAPPINGS[i as usize]),
        Err(_) => None,
    }
}

