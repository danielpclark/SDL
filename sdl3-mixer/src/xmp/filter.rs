/// `powf()`: upstream's build has it (`HAVE_POWF`); here, as the reference
/// was made, through the double-precision `pow()` of SDL's fdlibm.
#[inline]
fn powf(f1: f32, f2: f32) -> f32 {
    pow(f1 as f64, f2 as f64) as f32
}

/*
 * Simple 2-poles resonant filter
 */
const FREQ_PARAM_MULT: f32 = 128.0f32 / (24.0f32 * 256.0f32);
/// Translation of `libxmp_filter_setup()`: returns `(a0, b0, b1)`.
pub(crate) fn libxmp_filter_setup(srate: i32, mut cutoff: i32, mut res: i32) -> (i32, i32, i32) {
    let fs = srate as f32;

    /* [0-255] => [100Hz-8000Hz] */
    clamp(&mut cutoff, 0, 255);
    clamp(&mut res, 0, 255);

    let mut fc = 110.0f32 * powf(2.0f32, cutoff as f32 * FREQ_PARAM_MULT + 0.25f32);
    if fc > fs / 2.0f32 {
        fc = fs / 2.0f32;
    }

    let r: f32 = (fs as f64 / (2.0 * 3.14159265358979f32 as f64 * fc as f64)) as f32;
    let d: f32 = (RESONANCE_TABLE[(res >> 1) as usize] as f64 * (r as f64 + 1.0) - 1.0) as f32;
    let e: f32 = r * r;

    let fg: f32 = (1.0 / (1.0 + d as f64 + e as f64)) as f32;
    let fb0: f32 = ((d + e + e) as f64 / (1.0 + d as f64 + e as f64)) as f32;
    let fb1: f32 = (-e as f64 / (1.0 + d as f64 + e as f64)) as f32;

    (
        (fg * (1 << FILTER_SHIFT) as f32) as i32,
        (fb0 * (1 << FILTER_SHIFT) as f32) as i32,
        (fb1 * (1 << FILTER_SHIFT) as f32) as i32,
    )
}
