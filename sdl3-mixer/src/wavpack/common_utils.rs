pub(crate) fn wavpack_get_bytes_per_sample(wpc: &WavpackContext<'_>) -> i32 {
    wpc.config.bytes_per_sample
}

// Free all memory allocated for raw WavPack blocks (for all allocated streams)
// and free all additional streams. This does not free the default stream ([0])
// which is always kept around.

/// Translation of `free_streams()`, on the context's streams.
pub(crate) fn free_streams(streams: &mut Vec<Box<WavpackStream>>) {
    let mut si = streams.len();

    while si > 0 {
        si -= 1;
        free_single_stream(&mut streams[si]);

        if si != 0 {
            streams.pop();
        }
    }
}

// Free all resources associated with the specified stream

/// Translation of `free_single_stream()`.
pub(crate) fn free_single_stream(wps: &mut WavpackStream) {
    wps.blockbuff = None;
    wps.block2buff = None;

    // FIXME (upstream): a seek that fails after freeing the streams can
    // leave stream 0 with a header (the last one it found) that covers the
    // current position, and its old decoder state, so the next
    // WavpackUnpackSamples() carries on decoding without reading a block:
    // from the freed block's bitstreams and DSD data (upstream reads freed
    // memory) or the freed DSD tables (upstream reads through NULL). Here
    // they go with the block, so those samples come out muted.
    wps.wvbits = Bitstream::default();
    wps.wvcbits = Bitstream::default();
    wps.wvxbits = Bitstream::default();
    wps.dsd.data = Vec::new();
    wps.dsd.byteptr = 0;
    wps.dsd.endptr = 0;

    free_dsd_tables(wps);
}

// Free all DSD-related resources associated with the specified stream

/// Translation of `free_dsd_tables()`.
pub(crate) fn free_dsd_tables(wps: &mut WavpackStream) {
    wps.dsd.probabilities = None;
    wps.dsd.summed_probabilities = None;
    wps.dsd.lookup_buffer = None;
    wps.dsd.value_lookup = None;
    wps.dsd.ptable = None;
}

/// Translation of `WavpackFloatNormalize()`.
pub(crate) fn wavpack_float_normalize(values: &mut [i32], delta_exp: i32) {
    if delta_exp == 0 {
        return;
    }

    for fvalue in values.iter_mut() {
        let mut exp = get_exponent(*fvalue);
        if exp == 0 || exp + delta_exp <= 0 {
            *fvalue = 0;
        } else if exp == 255 || {
            exp += delta_exp;
            exp >= 255
        } {
            set_exponent(fvalue, 255);
            set_mantissa(fvalue, 0);
        } else {
            set_exponent(fvalue, exp);
        }
    }
}
