// This function obtains general information about an open input file and
// returns a mask with the following bit values:

// MODE_WVC:  a .wvc file has been found and will be used for lossless
// MODE_LOSSLESS:  file is lossless (either pure or hybrid)
// MODE_HYBRID:  file is hybrid mode (either lossy or lossless)
// MODE_FLOAT:  audio data is 32-bit ieee floating point
// MODE_VALID_TAG:  file contains a valid ID3v1 or APEv2 tag
// MODE_HIGH:  file was created in "high" mode (information only)
// MODE_FAST:  file was created in "fast" mode (information only)
// MODE_EXTRA:  file was created using "extra" mode (information only)
// MODE_APETAG:  file contains a valid APEv2 tag
// MODE_SFX:  file was created as a "self-extracting" executable
// MODE_VERY_HIGH:  file was created in the "very high" mode (or in
//                  the "high" mode prior to 4.4)
// MODE_MD5:  file contains an MD5 checksum
// MODE_XMODE:  level used for extra mode (1-6, 0=unknown)
// MODE_DNS:  dynamic noise shaping

/// Translation of `WavpackGetMode()`.
pub(crate) fn wavpack_get_mode(wpc: &WavpackContext<'_>) -> i32 {
    let mut mode = 0;

    if (wpc.config.flags & CONFIG_HYBRID_FLAG) != 0 {
        mode |= MODE_HYBRID;
    } else if (wpc.config.flags & CONFIG_LOSSY_MODE) == 0 {
        mode |= MODE_LOSSLESS;
    }

    if wpc.wvc_flag != 0 {
        mode |= MODE_LOSSLESS | MODE_WVC;
    }

    if wpc.lossy_blocks != 0 {
        mode &= !MODE_LOSSLESS;
    }

    if (wpc.config.flags & CONFIG_FLOAT_DATA) != 0 {
        mode |= MODE_FLOAT;
    }

    if (wpc.config.flags & (CONFIG_HIGH_FLAG | CONFIG_VERY_HIGH_FLAG)) != 0 {
        mode |= MODE_HIGH;

        if (wpc.config.flags & CONFIG_VERY_HIGH_FLAG) != 0
            || wpc.streams.first().is_some_and(|s| s.wphdr.version < 0x405)
        {
            mode |= MODE_VERY_HIGH;
        }
    }

    if (wpc.config.flags & CONFIG_FAST_FLAG) != 0 {
        mode |= MODE_FAST;
    }

    if (wpc.config.flags & CONFIG_EXTRA_MODE) != 0 {
        mode |= MODE_EXTRA | (wpc.config.xmode << 12);
    }

    if (wpc.config.flags & CONFIG_CREATE_EXE) != 0 {
        mode |= MODE_SFX;
    }

    if (wpc.config.flags & CONFIG_MD5_CHECKSUM) != 0 {
        mode |= MODE_MD5;
    }

    if (wpc.config.flags & CONFIG_HYBRID_FLAG) != 0
        && (wpc.config.flags & CONFIG_DYNAMIC_SHAPING) != 0
        && wpc
            .streams
            .first()
            .is_some_and(|s| s.wphdr.version >= 0x407)
    {
        mode |= MODE_DNS;
    }

    if valid_tag(&wpc.m_tag) != 0 {
        mode |= MODE_VALID_TAG;

        if valid_tag(&wpc.m_tag) == b'A' as i32 {
            mode |= MODE_APETAG;
        }
    }

    mode |= (wpc.config.qmode << 16) & 0xFF0000;

    mode
}

// This function returns a pointer to a string describing the last error
// generated by WavPack.

/// Translation of `WavpackGetErrorMessage()`.
pub(crate) fn wavpack_get_error_message<'b>(wpc: &'b WavpackContext<'_>) -> &'b str {
    &wpc.error_message
}

// Get total number of samples contained in the WavPack file, or -1 if unknown

/// Translation of `WavpackGetNumSamples64()`.
pub(crate) fn wavpack_get_num_samples64(wpc: &WavpackContext<'_>) -> i64 {
    wpc.total_samples
}

// Returns the sample rate of the specified WavPack file

/// Translation of `WavpackGetSampleRate()`.
pub(crate) fn wavpack_get_sample_rate(wpc: &WavpackContext<'_>) -> u32 {
    if wpc.dsd_multiplier != 0 {
        (wpc.config.sample_rate as u32).wrapping_mul(wpc.dsd_multiplier)
    } else {
        wpc.config.sample_rate as u32
    }
}

// Returns the number of channels of the specified WavPack file. Note that
// this is the actual number of channels contained in the file even if the
// OPEN_2CH_MAX flag was specified when the file was opened.

/// Translation of `WavpackGetNumChannels()`.
pub(crate) fn wavpack_get_num_channels(wpc: &WavpackContext<'_>) -> i32 {
    wpc.config.num_channels
}

// Returns the number of bytes used for each sample (1 to 4) in the original
