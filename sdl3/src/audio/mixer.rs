/// Mix audio data in a specified format. Translation of `SDL_MixAudio()`.
///
/// This takes an audio buffer `src` of the given format and mixes it into
/// `dst` (as much as both have room for), performing addition, volume
/// adjustment, and overflow clipping. The buffers must hold the same
/// format.
///
/// This is provided for convenience -- you can mix your own audio data.
///
/// Do not use this function for mixing together more than two streams of
/// sample data. The output from repeated application of this function may
/// be distorted by clipping, because there is no accumulator with greater
/// range than the input (not to mention this being an inefficient way of
/// doing it).
///
/// It is a common misconception that this function is required to write
/// audio data to an output stream in an audio callback. While you can do
/// that, `mix_audio` is really only needed when you're mixing a single
/// audio stream with a volume adjustment.
///
/// `volume` ranges from 0.0 to 1.0 (it can go higher, with clipping);
/// integer formats use it in 1/128 steps.
pub fn mix_audio(dst: &mut [u8], src: &[u8], format: AudioFormat, fvolume: f32) -> Result<()> {
    let volume = crate::stdlib::math::roundf(fvolume * MIX_MAXVOLUME as f32) as i32;
    let len = dst.len().min(src.len());
    let (dst, src) = (&mut dst[..len], &src[..len]);

    if volume == 0 {
        return Ok(());
    }

    // ADJUST_VOLUME(type, s, v): ((s) = (type)(((s) * (v)) / MIX_MAXVOLUME))
    match format {
        AudioFormat::U8 => {
            for (d, &s) in dst.iter_mut().zip(src) {
                // ADJUST_VOLUME_U8
                let src_sample = ((((s as i32 - 128) * volume) / MIX_MAXVOLUME) + 128) as u8;
                *d = MIX8[*d as usize + src_sample as usize];
            }
        }

        AudioFormat::S8 => {
            let max_audioval = i8::MAX as i32;
            let min_audioval = i8::MIN as i32;
            for (d, &s) in dst.iter_mut().zip(src) {
                let src_sample = ((s as i8 as i32 * volume) / MIX_MAXVOLUME) as i8;
                let dst_sample =
                    (*d as i8 as i32 + src_sample as i32).clamp(min_audioval, max_audioval);
                *d = dst_sample as i8 as u8;
            }
        }

        AudioFormat::S16LE | AudioFormat::S16BE => {
            let be = format == AudioFormat::S16BE;
            let max_audioval = i16::MAX as i32;
            let min_audioval = i16::MIN as i32;
            let rd = |b: &[u8]| {
                if be {
                    i16::from_be_bytes([b[0], b[1]])
                } else {
                    i16::from_le_bytes([b[0], b[1]])
                }
            };
            for (d, s) in dst.chunks_exact_mut(2).zip(src.chunks_exact(2)) {
                let src1 = ((rd(s) as i32 * volume) / MIX_MAXVOLUME) as i16;
                let src2 = rd(d);
                let dst_sample =
                    (src1 as i32 + src2 as i32).clamp(min_audioval, max_audioval) as i16;
                d.copy_from_slice(&if be {
                    dst_sample.to_be_bytes()
                } else {
                    dst_sample.to_le_bytes()
                });
            }
        }

        AudioFormat::S32LE | AudioFormat::S32BE => {
            let be = format == AudioFormat::S32BE;
            let max_audioval = i32::MAX as i64;
            let min_audioval = i32::MIN as i64;
            let rd = |b: &[u8]| {
                let a = [b[0], b[1], b[2], b[3]];
                if be {
                    i32::from_be_bytes(a)
                } else {
                    i32::from_le_bytes(a)
                }
            };
            for (d, s) in dst.chunks_exact_mut(4).zip(src.chunks_exact(4)) {
                let src1 = (rd(s) as i64 * volume as i64) / MIX_MAXVOLUME as i64;
                let src2 = rd(d) as i64;
                let dst_sample = (src1 + src2).clamp(min_audioval, max_audioval) as i32;
                d.copy_from_slice(&if be {
                    dst_sample.to_be_bytes()
                } else {
                    dst_sample.to_le_bytes()
                });
            }
        }

        AudioFormat::F32LE | AudioFormat::F32BE => {
            let be = format == AudioFormat::F32BE;
            let max_audioval = 1.0f32;
            let min_audioval = -1.0f32;
            let rd = |b: &[u8]| {
                let a = [b[0], b[1], b[2], b[3]];
                if be {
                    f32::from_be_bytes(a)
                } else {
                    f32::from_le_bytes(a)
                }
            };
            for (d, s) in dst.chunks_exact_mut(4).zip(src.chunks_exact(4)) {
                let src1 = rd(s) * fvolume;
                let src2 = rd(d);

                let mut dst_sample = src1 + src2;
                if dst_sample > max_audioval {
                    dst_sample = max_audioval;
                } else if dst_sample < min_audioval {
                    dst_sample = min_audioval;
                }
                d.copy_from_slice(&if be {
                    dst_sample.to_be_bytes()
                } else {
                    dst_sample.to_le_bytes()
                });
            }
        }

        // If this happens... FIXME!
        _ => return Err(Error::new("SDL_MixAudio(): unknown audio format")),
    }

    Ok(())
}
