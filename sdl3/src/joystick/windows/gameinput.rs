/// The driver's state (`g_GameInputList`, `g_pGameInput`, ...).
#[derive(Default)]
struct State {
    /// Translation of `g_GameInputList`.
    devices: Vec<InternalDevice>,
    /// Translation of `g_pGameInput`.
    game_input: Option<GameInputRef>,
    /// Translation of `g_GameInputCallbackToken`.
    callback_token: CallbackToken,
    /// Translation of `g_GameInputTimestampOffset`.
    timestamp_offset: u64,
    /// The open joysticks' `joystick->hwdata`.
    open: Vec<HwData>,
}

/// Guarded by the joystick lock upstream; the `RefCell` borrow is never
/// held across an event push or a call back into the joystick API.
static STATE: ReentrantMutex<RefCell<Option<State>>> = ReentrantMutex::new(RefCell::new(None));

fn with_state<R>(f: impl FnOnce(&mut State) -> R) -> R {
    let guard = STATE.lock();
    let mut state = guard.borrow_mut();
    f(state.get_or_insert_with(State::default))
}

/// A new reference to the `IGameInput` interface, if the driver has it.
fn game_input() -> Option<GameInput> {
    with_state(|s| s.game_input.as_ref().map(|g| GameInput::clone(g)))
}

/// SDL's timestamp of a GameInput timestamp (microseconds), in nanoseconds.
fn sdl_timestamp(timestamp_us: u64, offset: u64) -> u64 {
    timestamp_us.wrapping_add(offset).wrapping_mul(1000)
}

/// The offset of SDL's microsecond clock from GameInput's.
pub(super) fn timestamp_offset(now_ns: u64, game_input_us: u64) -> u64 {
    (now_ns / 1000).wrapping_sub(game_input_us)
}

/// Translation of `GAMEINPUT_InternalIsGamepad()`.
pub(super) fn is_gamepad(info: &DeviceInfo) -> bool {
    (info.supported_input & kind::GAMEPAD) != 0
}

/// Translation of `GAMEINPUT_GetDeviceRawType()`.
pub(super) fn device_raw_type(info: &DeviceInfo) -> RawType {
    if GAMEINPUT_API_VERSION >= 3 && (info.supported_input & kind::RAW_DEVICE_REPORT) != 0 {
        match (info.vendor_id, info.product_id) {
            (USB_VENDOR_MADCATZ, USB_PRODUCT_MADCATZ_XB1_STRATOCASTER_GUITAR) => {
                return RawType::RockBandGuitar
            }
            (USB_VENDOR_MADCATZ, USB_PRODUCT_MADCATZ_XB1_DRUM_KIT) => {
                return RawType::RockBandDrumKit
            }
            (USB_VENDOR_MADCATZ, USB_PRODUCT_MADCATZ_XB1_LEGACY_ADAPTER) => {
                return RawType::LegacyAdapter
            }
            (
                USB_VENDOR_PDP,
                USB_PRODUCT_PDP_XB1_JAGUAR_GUITAR | USB_PRODUCT_PDP_XB1_RIFFMASTER_GUITAR,
            ) => return RawType::RockBandGuitar,
            (USB_VENDOR_PDP, USB_PRODUCT_PDP_XB1_DRUM_KIT) => return RawType::RockBandDrumKit,
            (USB_VENDOR_CRKD, USB_PRODUCT_RED_OCTANE_XB1_STAGE_TOUR_GUITAR) => {
                return RawType::RockBandGuitar
            }
            (USB_VENDOR_RED_OCTANE, USB_PRODUCT_RED_OCTANE_XB1_GUITAR_HERO_LIVE_GUITAR) => {
                return RawType::GuitarHeroLiveGuitar
            }
            (USB_VENDOR_RED_OCTANE_GAMES, USB_PRODUCT_RED_OCTANE_XB1_STAGE_TOUR_GUITAR) => {
                return RawType::RockBandGuitar
            }
            (USB_VENDOR_RED_OCTANE_GAMES, USB_PRODUCT_RED_OCTANE_XB1_STAGE_TOUR_DRUMS) => {
                return RawType::RockBandDrumKit
            }
            _ => {}
        }
    }
    RawType::None
}

/// Translation of `GAMEINPUT_GetDeviceSubtype()`.
pub(super) fn device_subtype(info: &DeviceInfo) -> JoystickType {
    let supported_input = info.supported_input;
    let raw_type = device_raw_type(info);
    if raw_type == RawType::RockBandGuitar || raw_type == RawType::GuitarHeroLiveGuitar {
        return JoystickType::Guitar;
    }
    if raw_type == RawType::RockBandDrumKit {
        return JoystickType::DrumKit;
    }
    if (supported_input & kind::RACING_WHEEL) != 0 {
        return JoystickType::Wheel;
    }
    if (supported_input & kind::ARCADE_STICK) != 0 {
        return JoystickType::ArcadeStick;
    }
    if (supported_input & kind::FLIGHT_STICK) != 0 {
        return JoystickType::FlightStick;
    }
    if (supported_input & (kind::GAMEPAD | kind::CONTROLLER)) != 0 {
        return JoystickType::Gamepad;
    }
    // Other device subtypes don't have their own GameInputKind enum entries.
    JoystickType::Unknown
}

/// Translation of `GetSteamVirtualGamepadSlot()`.
pub(super) fn steam_virtual_gamepad_slot(device_path: &str) -> i32 {
    // The format for the raw input device path is documented here:
    // https://partner.steamgames.com/doc/features/steam_controller/steam_input_gamepad_emulation_bestpractices
    use Scan::*;
    scan_int(
        device_path,
        &[
            Lit("\\\\.\\pipe\\HID#VID_045E&PID_028E&IG_00#"),
            SkipHex,
            Lit("&"),
            SkipHex,
            Lit("&"),
            SkipHex,
            Lit("#"),
            Int,
            Lit("#"),
            SkipUnsigned,
        ],
    )
    .unwrap_or(-1)
}

/// Translation of `IsXbox360WirelessAdapter()`.
pub(super) fn is_xbox360_wireless_adapter(vendor: u16, product: u16) -> bool {
    vendor == USB_VENDOR_MICROSOFT
        && matches!(
            product,
            USB_PRODUCT_XBOX360_WIRELESS_RECEIVER
                | USB_PRODUCT_XBOX360_WIRELESS_RECEIVER_THIRDPARTY1
                | USB_PRODUCT_XBOX360_WIRELESS_RECEIVER_THIRDPARTY2
        )
}

/// The device path: the `APP_LOCAL_DEVICE_ID` as a hex string.
pub(super) fn device_path(device_id: &[u8]) -> String {
    device_id.iter().map(|b| format!("{b:02X}")).collect()
}

/// The manufacturer and product strings of a device. Translation of
/// `QueryDeviceName()`.
fn query_device_name(
    info: &DeviceInfo,
    vendor_id: u16,
    product_id: u16,
) -> (Option<String>, Option<String>) {
    let manufacturer_string =
        super::super::hidapi::get_device_manufacturer_name(vendor_id, product_id);
    let product_string = super::super::hidapi::get_device_product_name(vendor_id, product_id);
    if product_string.is_some() {
        return (manufacturer_string, product_string);
    }

    (None, info.display_name())
}

/// Translation of `GAMEINPUT_InternalAddOrFind()`.
fn internal_add_or_find(device: Device) {
    crate::joystick::assert_joysticks_locked();

    let info = device.info();
    // (info->capabilities & GameInputDeviceCapabilityWireless isn't checked
    // upstream: the bus is always USB)
    let bus = HARDWARE_BUS_USB;
    let vendor = info.vendor_id;
    let product = info.product_id;
    let version = 0u16;
    let mut driver_signature = b'g';
    let mut subtype = device_subtype(info);
    let raw_type = device_raw_type(info);

    let (manufacturer_string, product_string) = query_device_name(info, vendor, product);

    if is_xbox360_wireless_adapter(vendor, product)
        || should_ignore_joystick(vendor, product, version, product_string.as_deref())
        || joystick_handled_by_another_driver(
            GAMEINPUT_DRIVER_INDEX,
            vendor,
            product,
            version,
            product_string.as_deref(),
        )
    {
        return;
    }

    // This joystick backend currently doesn't provide a haptic backend, so fallback to DirectInput for haptic-capable devices.
    if hints::get_bool(hints::JOYSTICK_DIRECTINPUT, true)
        && info.force_feedback_motor_count > 0
        && device.is_force_feedback_motor_powered_on(0)
    {
        return;
    }

    if is_gamepad(info) {
        if !hints::get_bool(hints::JOYSTICK_GAMEINPUT, GAMEINPUT_DEFAULT) {
            return;
        }
    } else if raw_type == RawType::None {
        // Let other backends handle non-gamepad controllers to possibly avoid bugs and/or regressions.
        if hints::get_bool(hints::JOYSTICK_DIRECTINPUT, true) {
            return;
        }
        if (info.supported_input & kind::CONTROLLER) != 0 {
            // Maintain GUID compatibility with DirectInput controller mappings.
            driver_signature = 0;
            subtype = JoystickType::Unknown;
        } else {
            // This joystick backend currently doesn't provide proper reading of other joystick types.
            return;
        }
    }

    let found = with_state(|s| {
        match s.devices.iter_mut().find(|e| e.device.same(&device)) {
            Some(elem) => {
                // we're already added
                elem.is_delete_requested = false;
                true
            }
            None => false,
        }
    });
    if found {
        return;
    }

    let elem = InternalDevice {
        // Generate a device path
        path: device_path(&info.device_id),
        name: create_joystick_name(
            vendor,
            product,
            manufacturer_string.as_deref(),
            product_string.as_deref(),
        ),
        guid: create_joystick_guid(
            bus,
            vendor,
            product,
            version,
            manufacturer_string.as_deref(),
            product_string.as_deref(),
            driver_signature,
            subtype as u8,
        ),
        device_instance: crate::utils::next_object_id(),
        vendor,
        product,
        raw_type,
        steam_virtual_gamepad_slot: info
            .pnp_path()
            .map_or(-1, |p| steam_virtual_gamepad_slot(&p)),
        is_added: false,
        is_delete_requested: false,
        device: device.clone(),
    };
    with_state(|s| s.devices.push(elem));
}

/// Translation of `GAMEINPUT_InternalJoystickDeviceCallback()`.
unsafe extern "system" fn internal_joystick_device_callback(
    _callback_token: CallbackToken,
    _context: *mut c_void,
    device: *mut c_void,
    _timestamp: u64,
    current_status: u32,
    _previous_status: u32,
) {
    if device.is_null() {
        // This should never happen, but ignore it if it does
        return;
    }

    let _lock = lock_joysticks();

    if (current_status & DEVICE_CONNECTED) != 0 {
        // SAFETY: GameInput passes a live device.
        if let Ok(device) = unsafe { Device::from_borrowed(device) } {
            internal_add_or_find(device);
        }
        // (a failure sets the error "IGameInputDevice::GetDeviceInfo"
        // upstream, which nobody reads)
    } else {
        with_state(|s| {
            if let Some(elem) = s.devices.iter_mut().find(|e| e.device.is(device)) {
                // will be deleted on the next Detect call
                elem.is_delete_requested = true;
            }
        });
    }
}

/// Translation of `GAMEINPUT_IsRawGameInputEnabled()`.
fn is_raw_game_input_enabled() -> bool {
    GAMEINPUT_API_VERSION >= 3 && hints::get_bool(hints::JOYSTICK_GAMEINPUT_RAW, true)
}

/// Translation of `GAMEINPUT_InternalSystemButtonCallback()`; the context
/// is the joystick's instance ID.
unsafe extern "system" fn internal_system_button_callback(
    _callback_token: CallbackToken,
    context: *mut c_void,
    _device: *mut c_void,
    timestamp_us: u64,
    current_buttons: u32,
    previous_buttons: u32,
) {
    let joystick = context as usize as JoystickID;

    let changed_buttons = previous_buttons ^ current_buttons;
    if changed_buttons != 0 {
        let _lock = lock_joysticks();
        let timestamp = sdl_timestamp(timestamp_us, with_state(|s| s.timestamp_offset));

        for (button, down) in system_button_inputs(changed_buttons, current_buttons) {
            send_joystick_button(timestamp, joystick, button, down);
        }
    }
}

/// The joystick buttons of the system buttons that changed.
pub(super) fn system_button_inputs(changed_buttons: u32, current_buttons: u32) -> Vec<(u8, bool)> {
    let mut inputs = Vec::new();
    if (changed_buttons & system_buttons::GUIDE) != 0 {
        let down = (current_buttons & system_buttons::GUIDE) != 0;
        inputs.push((GamepadButton::Guide as u8, down));
    }
    if (changed_buttons & system_buttons::SHARE) != 0 {
        let down = (current_buttons & system_buttons::SHARE) != 0;
        inputs.push((GAMEPAD_BUTTON_GAMEINPUT_SHARE, down));
    }
    inputs
}

/// A joystick event of a reading, in the order upstream sends them.
#[derive(Clone, Copy, Debug, PartialEq)]
pub(super) enum Input {
    Button(u8, bool),
    Hat(u8, u8),
    Axis(u8, i16),
}

/// Send the events of a reading.
fn send_inputs(timestamp: u64, joystick: JoystickID, inputs: &[Input]) {
    for &input in inputs {
        match input {
            Input::Button(button, down) => send_joystick_button(timestamp, joystick, button, down),
            Input::Hat(hat, value) => send_joystick_hat(timestamp, joystick, hat, value),
            Input::Axis(axis, value) => send_joystick_axis(timestamp, joystick, axis, value),
        }
    }
}

/// The d-pad hat of the four direction bits of the raw instrument reports.
fn raw_dpad_hat(buttons: u16) -> u8 {
    let mut hat = HAT_CENTERED;
    if (buttons & 0x0100) != 0 {
        hat |= HAT_UP;
    }
    if (buttons & 0x0200) != 0 {
        hat |= HAT_DOWN;
    }
    if (buttons & 0x0400) != 0 {
        hat |= HAT_LEFT;
    }
    if (buttons & 0x0800) != 0 {
        hat |= HAT_RIGHT;
    }
    hat
}

/// The events of a drum kit's raw report (`len` bytes of `raw_data`).
/// Translation of `GAMEINPUT_DrumUpdate()`.
pub(super) fn drum_inputs(raw_data: &[u8; 40], len: usize) -> Vec<Input> {
    let mut inputs = Vec::new();
    let buttons = raw_data[0] as u16 | (raw_data[1] as u16) << 8;
    if len >= 6 {
        let mut hat = HAT_CENTERED;
        if (buttons & 0x0100) != 0 || (raw_data[4] & 0xf0) != 0 {
            hat |= HAT_UP;
        }
        if (buttons & 0x0200) != 0 || (raw_data[4] & 0x0f) != 0 {
            hat |= HAT_DOWN;
        }
        if (buttons & 0x0400) != 0 {
            hat |= HAT_LEFT;
        }
        if (buttons & 0x0800) != 0 {
            hat |= HAT_RIGHT;
        }
        inputs.push(Input::Hat(0, hat));
        // The rest of the instruments are mapped to PS3 style inputs
        // The PS3 used flags for dictating if a pad or a cymbal was hit, so we emulate that here
        let button = |b: GamepadButton, down: bool| Input::Button(b as u8, down);
        inputs.extend([
            button(GamepadButton::Back, (buttons & 0x0008) != 0),
            button(GamepadButton::Start, (buttons & 0x0004) != 0),
            button(GamepadButton::LeftShoulder, (buttons & 0x1000) != 0),
            button(GamepadButton::RightShoulder, (buttons & 0x2000) != 0),
            button(
                GamepadButton::South,
                (raw_data[3] & 0x0f) != 0 || (raw_data[5] & 0xf0) != 0 || (buttons & 0x0010) != 0,
            ),
            button(
                GamepadButton::East,
                (raw_data[2] & 0xf0) != 0 || (buttons & 0x0020) != 0,
            ),
            button(
                GamepadButton::West,
                (raw_data[3] & 0xf0) != 0 || (raw_data[4] & 0x0f) != 0 || (buttons & 0x0040) != 0,
            ),
            button(
                GamepadButton::North,
                (raw_data[2] & 0x0f) != 0 || (raw_data[4] & 0xf0) != 0 || (buttons & 0x0080) != 0,
            ),
            button(
                GamepadButton::LeftStick,
                raw_data[2] != 0 || raw_data[3] != 0,
            ),
            button(
                GamepadButton::RightStick,
                raw_data[4] != 0 || raw_data[5] != 0,
            ),
        ]);
    }
    inputs
}

/// Translation of `s_GuitarButtons`: the raw button of each joystick
/// button (0: not available).
const GUITAR_BUTTONS: [u16; 11] = [
    0x0010, // SDL_GAMEPAD_BUTTON_SOUTH
    0x0020, // SDL_GAMEPAD_BUTTON_EAST
    0x0040, // SDL_GAMEPAD_BUTTON_WEST
    0x0080, // SDL_GAMEPAD_BUTTON_NORTH
    0x0008, // SDL_GAMEPAD_BUTTON_BACK
    0,      // The guide button is not available
    0x0004, // SDL_GAMEPAD_BUTTON_START
    0,      // right joystick click unavailable
    0x4000, // SDL_GAMEPAD_BUTTON_RIGHT_STICK
    0x1000, // SDL_GAMEPAD_BUTTON_LEFT_SHOULDER
    0,      // right shoulder unavailable
];

/// Align pickup selector mappings with PS3 instruments
const EFFECTS_MAPPINGS: [i16; 5] = [-26880, -13568, -1792, 11008, 24576];

/// The events of a guitar's raw report (`len` bytes of `raw_data`).
/// Translation of `GAMEINPUT_GuitarUpdate()`.
pub(super) fn guitar_inputs(raw_data: &[u8; 40], len: usize) -> Vec<Input> {
    let mut inputs = Vec::new();
    let buttons = raw_data[0] as u16 | (raw_data[1] as u16) << 8;
    if len >= 10 {
        for (btnidx, &button_mask) in GUITAR_BUTTONS.iter().enumerate() {
            if button_mask == 0 {
                continue;
            }
            let down = (buttons & button_mask) != 0;
            inputs.push(Input::Button(btnidx as u8, down));
        }
        inputs.push(Input::Hat(0, raw_dpad_hat(buttons)));
        inputs.push(Input::Axis(
            GamepadAxis::RightX as u8,
            ((raw_data[3] as i32 * 257) - 32768) as i16,
        ));
        // PS3 RB guitars had tilt on right shoulder
        inputs.push(Input::Button(
            GamepadButton::RightShoulder as u8,
            raw_data[2] >= 0xD0,
        ));
        // PS3 RB guitars send L2 when using solo buttons
        inputs.push(Input::Axis(
            GamepadAxis::LeftTrigger as u8,
            if raw_data[6] != 0 { 32767 } else { -32768 },
        ));
        // Note (upstream): upstream indexes its five mappings with the top
        // nibble, reading past the table for 5 and up; here those send
        // nothing.
        if let Some(&effect) = EFFECTS_MAPPINGS.get((raw_data[4] >> 4) as usize) {
            inputs.push(Input::Axis(GamepadAxis::RightY as u8, effect));
        }
    }
    inputs
}

