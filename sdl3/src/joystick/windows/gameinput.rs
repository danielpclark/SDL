        let drums = info(USB_VENDOR_PDP, USB_PRODUCT_PDP_XB1_DRUM_KIT, raw);
        assert_eq!(device_raw_type(&drums), RawType::RockBandDrumKit);
        assert_eq!(device_subtype(&drums), JoystickType::DrumKit);
