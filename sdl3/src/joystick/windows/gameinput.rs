//! The GameInput joystick driver (`SDL_GAMEINPUT_JoystickDriver`), ahead
//! of the other Windows drivers: the gamepads GameInput reports (when the
//! `SDL_JOYSTICK_GAMEINPUT` hint is on, the default), with their guide and
//! share buttons, rumble, trigger rumble and motion sensors, and, from raw
//! device reports (`SDL_JOYSTICK_GAMEINPUT_RAW`), the Xbox One Rock Band
//! guitars and drum kits. GameInput calls the device callback on its own
//! thread; the devices are added to the joystick list on the next detect.
//!
//! Without GameInput (no DLL, as under Wine) the driver's init fails and
//! the other drivers pick the controllers up.

